"""Generates App/Features/Fitness/BodyMapData.swift from react-body-highlighter's
muscle polygons (MIT, (c) 2020 GV79) and renders a preview PNG.

Usage: python3 scripts/make_body_map.py <path to react-body-highlighter/src/assets/index.ts> [preview.png]
"""
import re
import sys

src = open(sys.argv[1]).read()

# Their muscle names -> our regions (Muscle raw values; "body" = always neutral).
MAP = {
    "CHEST": "chest", "OBLIQUES": "abdominals", "ABS": "abdominals", "BICEPS": "biceps",
    "TRICEPS": "triceps", "NECK": "neck", "FRONT_DELTOIDS": "shoulders", "BACK_DELTOIDS": "shoulders",
    "HEAD": "body", "KNEES": "body", "QUADRICEPS": "quadriceps", "CALVES": "calves",
    "FOREARM": "forearms", "TRAPEZIUS": "traps", "UPPER_BACK": "upperBack", "LOWER_BACK": "lower back",
    "GLUTEAL": "glutes", "HAMSTRING": "hamstrings", "LEFT_SOLEUS": "calves", "RIGHT_SOLEUS": "calves",
    "ABDUCTORS": "adductors", "ABDUCTOR": "abductors",
}


def parse(name):
    block = src.split(f"export const {name}")[1].split("export const")[0]
    out = []
    for muscle, body in re.findall(r"muscle:\s*MuscleType\.(\w+),\s*svgPoints:\s*\[(.*?)\]", block, re.S):
        for pts in re.findall(r"'([^']*)'", body):
            nums = [float(x) for x in pts.split()]
            out.append((MAP[muscle], nums))
    return out


front, back = parse("anteriorData"), parse("posteriorData")


def bounds(polys):
    xs = [v for _, n in polys for v in n[0::2]]
    ys = [v for _, n in polys for v in n[1::2]]
    return min(xs), min(ys), max(xs), max(ys)


def swift(name, polys):
    rows = []
    for region, nums in polys:
        values = ", ".join(f"{v:g}" for v in nums)
        rows.append(f'        ("{region}", [{values}]),')
    return f"    static let {name}: [(String, [Double])] = [\n" + "\n".join(rows) + "\n    ]\n"


fb, bb = bounds(front), bounds(back)
with open("App/Features/Fitness/BodyMapData.swift", "w") as f:
    f.write("// Generated by scripts/make_body_map.py. Do not edit by hand.\n")
    f.write("// Muscle outlines from react-body-highlighter (MIT License, Copyright (c) 2020 GV79),\n")
    f.write("// https://github.com/giavinh79/react-body-highlighter\n\n")
    f.write("import Foundation\n\n")
    f.write("/// Polygons as flat [x, y, x, y, ...] lists in the source's coordinate space.\n")
    f.write("nonisolated enum BodyMapData {\n")
    f.write(f"    /// Bounding box of all front polygons: minX, minY, maxX, maxY.\n")
    f.write(f"    static let frontBounds: [Double] = [{fb[0]:g}, {fb[1]:g}, {fb[2]:g}, {fb[3]:g}]\n")
    f.write(f"    static let backBounds: [Double] = [{bb[0]:g}, {bb[1]:g}, {bb[2]:g}, {bb[3]:g}]\n\n")
    f.write(swift("front", front) + "\n" + swift("back", back) + "}\n")
print("front", len(front), fb, "back", len(back), bb)

if len(sys.argv) > 2:
    from PIL import Image, ImageDraw
    S = 6
    img = Image.new("RGB", (220 * S, 210 * S), "white")
    d = ImageDraw.Draw(img)
    demo = {"chest": "#FF3B5C", "quadriceps": "#F59E0B", "shoulders": "#22C36A", "upperBack": "#FF3B5C", "glutes": "#F59E0B"}
    for ox, polys in ((5, front), (115, back)):
        for region, nums in polys:
            pts = [((nums[i] + ox) * S, (nums[i + 1] + 5) * S) for i in range(0, len(nums), 2)]
            d.polygon(pts, fill=demo.get(region, "#D5DAE1"), outline="white")
    img.save(sys.argv[2])
